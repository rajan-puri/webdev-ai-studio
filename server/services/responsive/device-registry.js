function getDeviceById(id) {
  return DEVICES.find(d => d.id === id) || null;
}

function getDevicesByCategory(category) {
  if (!category || category === 'all') return DEVICES;
  if (category === 'popular') return DEVICES.filter(d => d.category === 'popular');
  return DEVICES.filter(d => d.subCategory === category || d.category === category);
}

